// ---------- Class video call (Jitsi Meet, opened as a real separate browser window) ----------
// A genuine second OS window -- not an in-page iframe -- is what actually makes it "follow you
// across every page without cutting": since it isn't part of this page's DOM, navigating the
// main tab to a different route has zero effect on it. It keeps running until the user closes
// it or clicks "Leave meeting" inside Jitsi's own UI, which already provides camera/mic toggle,
// screen share, and leave -- no custom controls needed.
function openClassCall(room, displayName) {
  const url =
    `https://meet.jit.si/${encodeURIComponent(room)}` +
    `#userInfo.displayName="${encodeURIComponent(displayName || "")}"` +
    `&config.prejoinPageEnabled=false`;
  const w = 380, h = 660;
  const left = Math.max((window.screen.availWidth || 1200) - w - 24, 0);
  const top = Math.max((window.screen.availHeight || 800) - h - 24, 0);
  window.open(url, "classCall", `width=${w},height=${h},left=${left},top=${top}`);
}

// Render LaTeX math (delimited by $...$ or $$...$$) inside an element via KaTeX.
// Quiz text is generated by the AI using these delimiters -- see QUIZ_SYSTEM_PROMPT in app.py.
function renderMathIn(el) {
  if (!el || typeof renderMathInElement !== "function") return;
  renderMathInElement(el, {
    delimiters: [
      { left: "$$", right: "$$", display: true },
      { left: "$", right: "$", display: false },
    ],
    throwOnError: false,
  });
}

// ---------- Graph plotting (equation or points, from a question's optional "graph" field) ----------
// Safe recursive-descent evaluator for simple function-of-x expressions -- no eval()/Function().
// Supports: + - * / ^, unary minus, parentheses, x, pi, e, and sin/cos/tan/sqrt/abs/log/ln/exp.
function evalMathExpr(expr, xVal) {
  const src = expr.replace(/\s+/g, "");
  let pos = 0;

  function peek() { return src[pos]; }
  function consume(ch) {
    if (src[pos] !== ch) throw new Error(`Expected "${ch}" at position ${pos}`);
    pos++;
  }

  function parseNumber() {
    const start = pos;
    while (pos < src.length && /[0-9.]/.test(src[pos])) pos++;
    if (pos === start) throw new Error("Expected number");
    return parseFloat(src.slice(start, pos));
  }

  function parseIdent() {
    const start = pos;
    while (pos < src.length && /[a-zA-Z]/.test(src[pos])) pos++;
    return src.slice(start, pos);
  }

  const FUNCS = {
    sin: Math.sin, cos: Math.cos, tan: Math.tan,
    sqrt: Math.sqrt, abs: Math.abs, exp: Math.exp,
    log: Math.log10, ln: Math.log,
  };
  const CONSTS = { pi: Math.PI, e: Math.E };

  function parseAtom() {
    if (peek() === "(") {
      consume("(");
      const v = parseExpr();
      consume(")");
      return v;
    }
    if (/[0-9.]/.test(peek())) return parseNumber();
    if (/[a-zA-Z]/.test(peek())) {
      const ident = parseIdent();
      if (ident === "x") return xVal;
      if (ident in CONSTS) return CONSTS[ident];
      if (ident in FUNCS) {
        consume("(");
        const arg = parseExpr();
        consume(")");
        return FUNCS[ident](arg);
      }
      throw new Error(`Unknown identifier "${ident}"`);
    }
    throw new Error(`Unexpected character "${peek()}" at position ${pos}`);
  }

  function parsePow() {
    const base = parseAtom();
    if (peek() === "^") {
      consume("^");
      const exp = parseUnary(); // right-associative; allows e.g. 2^-1
      return Math.pow(base, exp);
    }
    return base;
  }

  // Unary minus/plus must bind LOOSER than exponentiation so that -x^2 means -(x^2),
  // matching standard math convention, not (-x)^2.
  function parseUnary() {
    if (peek() === "-") {
      consume("-");
      return -parseUnary();
    }
    if (peek() === "+") {
      consume("+");
      return parseUnary();
    }
    return parsePow();
  }

  function parseTerm() {
    let value = parseUnary();
    while (peek() === "*" || peek() === "/") {
      const op = peek();
      consume(op);
      const rhs = parseUnary();
      value = op === "*" ? value * rhs : value / rhs;
    }
    return value;
  }

  function parseExpr() {
    let value = parseTerm();
    while (peek() === "+" || peek() === "-") {
      const op = peek();
      consume(op);
      const rhs = parseTerm();
      value = op === "+" ? value + rhs : value - rhs;
    }
    return value;
  }

  const result = parseExpr();
  if (pos !== src.length) throw new Error(`Unexpected trailing input at position ${pos}`);
  return result;
}

function renderGraphIn(container, graph) {
  if (!container || !graph || typeof Chart === "undefined") return;

  let dataset;
  if (graph.type === "equation") {
    const xMin = typeof graph.x_min === "number" ? graph.x_min : -10;
    const xMax = typeof graph.x_max === "number" ? graph.x_max : 10;
    const points = [];
    const steps = 300;
    for (let i = 0; i <= steps; i++) {
      const x = xMin + ((xMax - xMin) * i) / steps;
      try {
        const y = evalMathExpr(graph.equation, x);
        if (Number.isFinite(y)) points.push({ x, y });
      } catch {
        // Skip points where the expression is undefined (e.g. sqrt of a negative, log of 0) --
        // this naturally creates gaps in the plotted curve, which is the correct behavior.
      }
    }
    dataset = { data: points, showLine: true, pointRadius: 0, borderWidth: 2.5, tension: 0 };
  } else if (graph.type === "points") {
    const points = graph.points.map(([x, y]) => ({ x, y }));
    dataset = { data: points, showLine: false, pointRadius: 5, pointHoverRadius: 6 };
  } else {
    return;
  }

  // Server-side validation should already guarantee an equation graph has real points, but
  // stay defensive: an empty chart with no data looks broken (Chart.js falls back to a bare
  // 0..1 grid), so just skip rendering entirely rather than show that.
  if (!dataset.data.length) return;

  const canvas = document.createElement("canvas");
  canvas.className = "quiz-graph-canvas";
  container.appendChild(canvas);

  const gridColor = "rgba(128,128,128,0.18)";
  const zeroLineColor = "rgba(128,128,128,0.55)";
  const tickColor = "rgba(128,128,128,0.9)";

  const chart = new Chart(canvas, {
    type: "scatter",
    data: {
      datasets: [{
        ...dataset,
        borderColor: "#4f46e5",
        backgroundColor: "#4f46e5",
      }],
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      animation: false,
      resizeDelay: 0,
      layout: { padding: { top: 10, right: 14, bottom: 10, left: 10 } },
      plugins: { legend: { display: false } },
      // Desmos-style: axes cross through the origin instead of being pinned to the plot's
      // edges, no axis-name labels (just the numbers), light gridlines with the zero lines
      // emphasized -- reads as a clean coordinate plane rather than a boxed chart.
      scales: {
        x: {
          type: "linear",
          position: "center",
          grid: {
            color: (ctx) => (ctx.tick.value === 0 ? zeroLineColor : gridColor),
            lineWidth: (ctx) => (ctx.tick.value === 0 ? 1.5 : 1),
          },
          ticks: { color: tickColor, font: { size: 11 }, padding: 4 },
        },
        y: {
          type: "linear",
          position: "center",
          grid: {
            color: (ctx) => (ctx.tick.value === 0 ? zeroLineColor : gridColor),
            lineWidth: (ctx) => (ctx.tick.value === 0 ? 1.5 : 1),
          },
          ticks: { color: tickColor, font: { size: 11 }, padding: 4 },
        },
      },
    },
  });

  // Chart.js's responsive sizing reads the canvas's parent container's layout box at
  // construction time -- when several graphs are created back-to-back in the same tick (e.g.
  // rendering a whole quiz's worth of questions at once), the browser hasn't necessarily
  // settled layout yet and the chart can measure a wrong/zero size and never self-correct.
  // Forcing one resize on the next animation frame (after layout has definitely settled)
  // fixes that without waiting on anything fragile like a timeout.
  requestAnimationFrame(() => chart.resize());
}

// Sidebar collapse
(function () {
  const btn = document.getElementById("collapseBtn");
  const sidebar = document.getElementById("sidebar");
  if (!btn || !sidebar) return;

  if (localStorage.getItem("sidebarCollapsed") === "true") {
    sidebar.classList.add("collapsed");
  }

  btn.addEventListener("click", () => {
    sidebar.classList.toggle("collapsed");
    localStorage.setItem("sidebarCollapsed", sidebar.classList.contains("collapsed"));
  });
})();

// Interactive quiz renderer (used on the take-quiz page)
function renderQuizQuestions(questions, container) {
  container.innerHTML = questions
    .map((p, pi) => {
      const choices = Array.isArray(p.choices) ? p.choices : [];
      const choicesHtml = choices
        .map(
          (c, ci) => `
            <button class="choice-btn" data-problem="${pi}" data-choice="${ci}">
              <span class="choice-label">${escapeHtml(c.label || "")}</span>
              ${escapeHtml(c.text || "")}
            </button>
          `
        )
        .join("");

      return `
        <div class="quiz-question" data-problem="${pi}">
          <span class="num">${pi + 1}.</span> ${escapeHtml(p.question || "")}
          ${p.graph ? `<div class="quiz-graph" id="graph-${pi}"></div>` : ""}
          <div class="quiz-choices">${choicesHtml}</div>
          <p class="quiz-feedback" id="feedback-${pi}"></p>
          <button class="steps-toggle" data-problem="${pi}">Show step-by-step solution</button>
          <div class="steps" id="steps-${pi}" hidden>${escapeHtml(p.solution || "")}</div>
        </div>
      `;
    })
    .join("");

  questions.forEach((p, pi) => {
    if (p.graph) renderGraphIn(document.getElementById(`graph-${pi}`), p.graph);
  });

  container.addEventListener("click", (e) => {
    const choiceBtn = e.target.closest(".choice-btn");
    if (choiceBtn) {
      handleQuizChoiceClick(questions, choiceBtn);
      return;
    }
    const stepsBtn = e.target.closest(".steps-toggle");
    if (stepsBtn) {
      const pi = stepsBtn.dataset.problem;
      const stepsEl = document.getElementById(`steps-${pi}`);
      stepsEl.hidden = !stepsEl.hidden;
      stepsBtn.textContent = stepsEl.hidden ? "Show step-by-step solution" : "Hide step-by-step solution";
    }
  });

  renderMathIn(container);
}

function handleQuizChoiceClick(questions, choiceBtn) {
  const pi = parseInt(choiceBtn.dataset.problem, 10);
  const ci = parseInt(choiceBtn.dataset.choice, 10);
  const problem = questions[pi];
  const choice = problem.choices[ci];
  const problemEl = document.querySelector(`.quiz-question[data-problem="${pi}"]`);
  const feedbackEl = document.getElementById(`feedback-${pi}`);

  if (problemEl.dataset.answered === "true") return;
  problemEl.dataset.answered = "true";

  problemEl.querySelectorAll(".choice-btn").forEach((btn) => {
    const c = problem.choices[parseInt(btn.dataset.choice, 10)];
    if (c.correct) btn.classList.add("correct");
    btn.disabled = true;
  });

  if (choice.correct) {
    feedbackEl.textContent = "Correct!";
    feedbackEl.className = "quiz-feedback correct-text";
  } else {
    choiceBtn.classList.add("incorrect");
    feedbackEl.textContent = choice.explanation || "That's not right.";
    feedbackEl.className = "quiz-feedback incorrect-text";
  }
  renderMathIn(feedbackEl);
}

function escapeHtml(str) {
  const div = document.createElement("div");
  div.textContent = str;
  return div.innerHTML;
}

// Reveal-on-scroll: sections stay hidden until scrolled into view.
(function () {
  const targets = document.querySelectorAll(".reveal-on-scroll");
  if (!targets.length) return;
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15 }
  );
  targets.forEach((el) => observer.observe(el));
})();
